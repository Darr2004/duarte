<script>
  (function () {
    var categorySelect = document.getElementById('category_id');
    var qrCheckbox = document.getElementById('generate_qr');
    var qrHint = document.getElementById('generateQrHint');
    var variantToggle = document.getElementById('hasVariantsToggle');
    // Once the user manually touches the checkbox, stop auto-deciding it
    // for them on every category change. On a failed-submit redisplay,
    // treat their prior choice as already "touched" so it isn't overwritten.
    var qrTouchedByUser = <?= $_SERVER['REQUEST_METHOD'] === 'POST' ? 'true' : 'false' ?>;

    if (!categorySelect || !qrCheckbox) { return; }
    qrCheckbox.addEventListener('change', function () { qrTouchedByUser = true; });

    function syncQr() {
      var hasVariants = variantToggle && variantToggle.checked;
      qrCheckbox.disabled = false;
      qrHint.textContent = hasVariants
        ? 'Auto-generates QR per variant.'
        : 'Auto-generates QR per unit.';
      if (!qrTouchedByUser) {
        var opt = categorySelect.options[categorySelect.selectedIndex];
        var mode = opt ? opt.dataset.borrowMode : null;
        qrCheckbox.checked = (mode === 'borrow' || mode === 'choice');
      }
    }

    categorySelect.addEventListener('change', syncQr);
    if (variantToggle) { variantToggle.addEventListener('change', syncQr); }
    syncQr();
  })();
</script>

