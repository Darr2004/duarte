$pdo = get_db();
$user = current_user();
$errors = [];
$values = [
    'item_code' => '', 'name' => '', 'brand' => '', 'description' => '', 'specification' => '', 'category_id' => '',
    'unit' => 'pc', 'quantity_on_hand' => 0,
    'variant_label' => '', 'stall_layer_id' => '',
    'generate_qr' => false,
];
// Each: ['value' => string, 'qty' => int]. Re-populated from POST on a
// failed submit so the rows the user typed aren't lost.
$variant_rows = [];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    if (!csrf_check($_POST['csrf_token'] ?? null)) {
        $errors[] = 'Your session expired. Please try again.';
    } else {
        $values['item_code']        = trim($_POST['item_code'] ?? '');
        $values['name']             = trim($_POST['name'] ?? '');
        $values['brand']            = trim($_POST['brand'] ?? '');
        $values['description']      = trim($_POST['description'] ?? '');
        $values['specification']    = trim($_POST['specification'] ?? '');
        $values['category_id']      = ($_POST['category_id'] ?? '') ?: null;
        $values['unit']             = trim($_POST['unit'] ?? 'pc') ?: 'pc';
        $values['quantity_on_hand'] = (int)($_POST['quantity_on_hand'] ?? 0);
        $values['variant_label']    = trim($_POST['variant_label'] ?? '');
        $values['stall_layer_id']   = ($_POST['stall_layer_id'] ?? '') ?: null;
        $values['generate_qr']      = !empty($_POST['generate_qr']);
        $borrow_mode = category_borrow_mode($pdo, $values['category_id'] ? (int)$values['category_id'] : null);
        $is_borrowable = borrow_mode_is_borrowable($borrow_mode) ? 1 : 0;

        $parsed = parse_variant_submission($_POST, [], $values['variant_label']);
        $variant_rows = $parsed['rows'];
        $errors = array_merge($errors, $parsed['errors']);

        if ($variant_rows && $values['variant_label'] === '') {
            $errors[] = 'Give the variant a label (e.g. "Size", "Amperage", "Color") since options were entered.';
        }
        if (!$variant_rows) {
            $values['variant_label'] = ''; // no options means no label either
        }

        $errors = array_merge($errors, validate_item_common_fields($values));
        if (!$variant_rows && $values['quantity_on_hand'] < 0) {
            $errors[] = 'Quantity on hand cannot be negative.';
        }

        // The item code field is auto-generated by category on the
        // client side and kept read-only, but if it ever arrives blank
        // (JS disabled, direct POST, etc.) fall back to generating it
        // here so a submission never fails just for a missing code.
        if ($values['item_code'] === '') {
            $values['item_code'] = next_item_code_for_category($pdo, $values['category_id'] ? (int)$values['category_id'] : null);
        }

        $image_filename = null;
        if (!$errors) {
            try {
                $image_filename = handle_item_image_upload($_FILES['image'] ?? []);
            } catch (RuntimeException $e) {
                $errors[] = $e->getMessage();
            }
        }

        if (!$errors) {
            // Up to 3 attempts: the item code came from a read-only field
            // pre-filled by JS, so on the rare chance two people submit for
            // the same category at nearly the same moment and collide on
            // the UNIQUE item_code constraint, just mint the next code and
            // retry instead of bouncing the whole form back to the user.
            $max_attempts = 3;
            for ($attempt = 1; $attempt <= $max_attempts; $attempt++) {
                try {
                    $pdo->beginTransaction();

                    $stmt = $pdo->prepare(
                        'INSERT INTO items (item_code, name, brand, description, specification, category_id, unit,
                         quantity_on_hand, is_borrowable, borrow_mode, variant_label, image_filename, stall_layer_id)
                         VALUES (:item_code, :name, :brand, :description, :specification, :category_id, :unit,
                         0, :is_borrowable, :borrow_mode, :variant_label, :image_filename, :stall_layer_id)'
                    );
                    $stmt->execute([
                        'item_code'        => $values['item_code'],
                        'name'             => $values['name'],
                        'brand'            => $values['brand'] ?: null,
                        'description'      => $values['description'] ?: null,
                        'specification'    => $values['specification'] ?: null,
                        'category_id'      => $values['category_id'],
                        'unit'             => $values['unit'],
                        'is_borrowable'    => $is_borrowable,
                        'borrow_mode'      => $borrow_mode,
                        'variant_label'    => $values['variant_label'] ?: null,
                        'image_filename'   => $image_filename,
                        'stall_layer_id'   => $values['stall_layer_id'],
                    ]);
                    $new_item_id = (int)$pdo->lastInsertId();

                    // Populated below when this item has options, so the QR
                    // generation step further down knows each option's id and
                    // starting qty and can scope tags to the specific option
                    // — mirrors how stock_in.php already scopes tags to
                    // whichever option was picked there.
                    $created_variants = [];
                    if ($variant_rows) {
                        // Each variant gets its own row, and its own initial-stock
                        // movement (which also rolls the item's aggregate total
                        // up by the same amount — see record_stock_movement()).
                        $variant_ins = $pdo->prepare(
                            'INSERT INTO item_variants (item_id, variant_value, variant_note, quantity_on_hand) VALUES (:item_id, :value, :note, 0)'
                        );
                        foreach ($variant_rows as $row) {
                            $variant_ins->execute(['item_id' => $new_item_id, 'value' => $row['value'], 'note' => $row['note']]);
                            $variant_id = (int)$pdo->lastInsertId();
                            $created_variants[] = ['id' => $variant_id, 'value' => $row['value'], 'qty' => $row['qty']];
                            if ($row['qty'] > 0) {
                                record_stock_movement(
                                    $pdo, $new_item_id, 'stock_in', $row['qty'],
                                    'initial_stock', null, $user['id'],
                                    'Initial stock at item creation (' . $row['value'] . ')', $variant_id
                                );
                            }
                        }
                    } elseif ($values['quantity_on_hand'] > 0) {
                        record_stock_movement(
                            $pdo, $new_item_id, 'stock_in', $values['quantity_on_hand'],
                            'initial_stock', null, $user['id'], 'Initial stock at item creation'
                        );
                    }

                    log_audit_event($pdo, $user, 'item_create', 'item', $new_item_id,
                        $user['full_name'] . ' added item "' . $values['name'] . '" (' . $values['item_code'] . ') to the catalog.');

                    $pdo->commit();

                    // Optional: generate QR asset tag(s) for the starting stock
                    // right away, so there's no separate trip to Register Asset.
                    // For a variant item, one lot/set-of-units is generated PER
                    // OPTION that was actually given starting stock, scoped to
                    // that option's item_variant_id — the same scoping
                    // stock_in.php already does when adding stock later. (An
                    // earlier version of this page disabled the checkbox for
                    // variant items entirely, from before assets.item_variant_id
                    // existed to make this possible — that restriction no
                    // longer applies.)
                    $created_tags = [];
                    if ($values['generate_qr']) {
                        // ['variant_id' => int|null, 'label_bit' => string, 'qty' => int]
                        $qr_lines = [];
                        if ($created_variants) {
                            foreach ($created_variants as $cv) {
                                if ($cv['qty'] > 0) {
                                    $qr_lines[] = ['variant_id' => $cv['id'], 'label_bit' => ' (' . $cv['value'] . ')', 'qty' => $cv['qty']];
                                }
                            }
                        } elseif ($values['quantity_on_hand'] > 0) {
                            $qr_lines[] = ['variant_id' => null, 'label_bit' => '', 'qty' => $values['quantity_on_hand']];
                        }

                        if ($qr_lines) {
                            $initial_location = null;
                            if (!empty($values['stall_layer_id'])) {
                                $sl_stmt = $pdo->prepare('SELECT r.room_number, s.stall_number, sl.layer_name FROM stall_layers sl JOIN stalls s ON s.id = sl.stall_id JOIN rooms r ON r.id = s.room_id WHERE sl.id = :id');
                                $sl_stmt->execute(['id' => $values['stall_layer_id']]);
                                $sl_row = $sl_stmt->fetch();
                                if ($sl_row) {
                                    $initial_location = 'Room ' . $sl_row['room_number'] . ' · Stall ' . $sl_row['stall_number'] . ' — ' . $sl_row['layer_name'];
                                }
                            }

                            try {
                                $pdo->beginTransaction();
                                foreach ($qr_lines as $line) {
                                    if (borrow_mode_is_borrowable($borrow_mode)) {
                                        for ($i = 0; $i < $line['qty']; $i++) {
                                            $tag = generate_unique_asset_tag($pdo);
                                            $ins = $pdo->prepare(
                                                'INSERT INTO assets (item_id, item_variant_id, asset_tag, serial_number, quantity, condition_note, location_note, acquired_at, registered_by)
                                                 VALUES (:item_id, :variant_id, :tag, NULL, 1, NULL, :loc, :acquired_at, :by)'
                                            );
                                            $ins->execute([
                                                'item_id'     => $new_item_id,
                                                'variant_id'  => $line['variant_id'],
                                                'tag'         => $tag,
                                                'loc'         => $initial_location,
                                                'acquired_at' => date('Y-m-d'),
                                                'by'          => $user['id'],
                                            ]);
                                            $asset_id = (int)$pdo->lastInsertId();
                                            record_asset_event(
                                                $pdo, $asset_id, 'registered', $user,
                                                'Registered as a tracked unit of ' . $values['name'] . $line['label_bit'] . ' (generated at item creation).'
                                            );
                                            $created_tags[] = $tag;
                                        }
                                    } else {
                                        $tag = generate_unique_asset_tag($pdo);
                                        $ins = $pdo->prepare(
                                            'INSERT INTO assets (item_id, item_variant_id, asset_tag, serial_number, quantity, condition_note, location_note, acquired_at, registered_by)
                                             VALUES (:item_id, :variant_id, :tag, NULL, :qty, NULL, :loc, :acquired_at, :by)'
                                        );
                                        $ins->execute([
                                            'item_id'     => $new_item_id,
                                            'variant_id'  => $line['variant_id'],
                                            'tag'         => $tag,
                                            'qty'         => $line['qty'],
                                            'loc'         => $initial_location,
                                            'acquired_at' => date('Y-m-d'),
                                            'by'          => $user['id'],
                                        ]);
                                        $asset_id = (int)$pdo->lastInsertId();
                                        record_asset_event(
                                            $pdo, $asset_id, 'registered', $user,
                                            'Registered as a lot of ' . $line['qty'] . ' ' . $values['name'] . $line['label_bit'] . ' (generated at item creation).'
                                        );
                                        $created_tags[] = $tag;
                                    }
                                }
                                log_audit_event($pdo, $user, 'asset_register', 'item', $new_item_id,
                                    $user['full_name'] . ' generated ' . count($created_tags) . ' QR tag(s) for "' . $values['name'] . '" at creation.');
                                $pdo->commit();
                            } catch (Exception $e) {
                                if ($pdo->inTransaction()) {
                                    $pdo->rollBack();
                                }
                                error_log($e->getMessage());
                                // The item itself is already saved — QR generation
                                // failing here shouldn't undo that or block the user.
                                $created_tags = [];
                            }
                        }
                    }

                    if ($created_tags) {
                        header('Location: ' . BASE_URL . '/inventory/asset_add.php?print_tags=' . urlencode(implode(',', $created_tags)));
                    } else {
                        header('Location: ' . BASE_URL . '/inventory/items.php');
                    }
                    exit;
                } catch (Exception $e) {
                    $pdo->rollBack();
                    $is_code_collision = $e instanceof PDOException && $e->getCode() === '23000'
                        && stripos($e->getMessage(), 'item_code') !== false;

                    if ($is_code_collision && $attempt < $max_attempts) {
                        $values['item_code'] = next_item_code_for_category($pdo, $values['category_id'] ? (int)$values['category_id'] : null);
                        continue;
                    }

                    delete_item_image($image_filename);
                    $errors[] = $is_code_collision
                        ? 'That item code is already in use.'
                        : 'Something went wrong. Please try again.';
                    break;
                }
            }
        }
    }
}

